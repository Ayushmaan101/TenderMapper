"""Checklist 4.4 verification — unit-level (no Streamlit).

Covers: sheet-name sanitization (invalid chars, >31 char truncation,
blank fallback, case-insensitive de-duplication that still respects the
31-char limit with a suffix appended); filename sanitization (normal,
blank, special characters, Windows trailing dot/space rule,
fully-invalid names); a real workbook built against the actual seeded
schema producing exactly 2 sheets matching the 10-item and 13-item
tables, with correct headers/formatting/verbatim requirement text;
manual edits (a hand-built results_store) appearing exactly in the
generated bytes; a reconfigured schema with different table counts,
custom names, special characters, and a genuine sheet-name collision
producing valid, openable files; and the empty/zero-table/zero-column
edge cases.

Every workbook built in this suite is round-tripped through
openpyxl.load_workbook() on its exported bytes - the most direct proof
of "produces valid, openable Excel files."

Run: python tests/verify_excel_export_unit.py
"""
from __future__ import annotations

import io
